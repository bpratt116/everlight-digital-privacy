#!/usr/bin/env node
/* Everlight Digital — Margin FAQ generator.
 *
 * Margin's own answers file (Podcasts/Help/help.json) is the ONE source for
 * the FAQ. The in-app Help screen reads it, and this script writes the same
 * answers into margin/support.html between fenced markers. Never hand-edit
 * the generated block.
 *
 * After editing Margin's help.json:
 *   node tools/margin-help.mjs <path-to-help.json>
 * then commit and push (a push to main publishes the site).
 *
 *   node tools/margin-help.mjs [path]           # write
 *   node tools/margin-help.mjs --check [path]   # exit 1 if the page is out of date
 *
 * The path comes from the first non-flag argument, else env MARGIN_HELP_JSON,
 * else ../Podcasts/Podcasts/Help/help.json relative to this repo's root.
 * A missing or malformed file is a hard error (non-zero exit), never a skip.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const START = '<!-- margin-help:start (generated by tools/margin-help.mjs from Margin\'s help.json — do not hand-edit) -->';
const END = '<!-- margin-help:end -->';
const CHECK = process.argv.includes('--check');

const ROOT = path.resolve(import.meta.dirname, '..');
const PAGE = path.join(ROOT, 'margin', 'support.html');

const argPath = process.argv.slice(2).find((a) => !a.startsWith('--'));
const SOURCE = path.resolve(
  argPath ?? process.env.MARGIN_HELP_JSON ?? path.join(ROOT, '..', 'Podcasts', 'Podcasts', 'Help', 'help.json'),
);

function fail(msg) {
  console.error(`margin-help: ${msg}`);
  process.exit(1);
}

const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function load() {
  let raw;
  try {
    raw = readFileSync(SOURCE, 'utf8');
  } catch (err) {
    fail(`cannot read ${SOURCE}: ${err.message}`);
  }
  let data;
  try {
    data = JSON.parse(raw);
  } catch (err) {
    fail(`${SOURCE} is not valid JSON: ${err.message}`);
  }
  if (!data || !Array.isArray(data.sections) || data.sections.length === 0) {
    fail(`${SOURCE} has no "sections" array`);
  }
  const seen = new Set();
  for (const s of data.sections) {
    if (typeof s.title !== 'string' || !s.title.trim() || !Array.isArray(s.items)) {
      fail(`${SOURCE}: every section needs a title and an items array`);
    }
    for (const i of s.items) {
      for (const k of ['id', 'question', 'answer']) {
        if (typeof i[k] !== 'string' || !i[k].trim()) fail(`${SOURCE}: item missing "${k}" in section "${s.title}"`);
      }
      if (!/^[a-z0-9-]+$/.test(i.id)) fail(`${SOURCE}: bad id "${i.id}"`);
      if (seen.has(i.id)) fail(`${SOURCE}: duplicate id "${i.id}"`);
      seen.add(i.id);
    }
  }
  return data;
}

const paragraphs = (answer) =>
  answer.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean);

function render(data) {
  const out = data.sections.map((s) => {
    const items = s.items.map((i) => {
      const ps = paragraphs(i.answer).map((p) => `<p>${esc(p)}</p>`).join('\n');
      return `<h3 id="${esc(i.id)}">${esc(i.question)}</h3>\n${ps}`;
    }).join('\n\n');
    return `<h2>${esc(s.title)}</h2>\n\n${items}`;
  }).join('\n\n');
  return `${START}\n\n${out}\n\n${END}`;
}

const data = load();
const block = render(data);

const html = readFileSync(PAGE, 'utf8');
const a = html.indexOf(START);
const b = html.indexOf(END);
let next;
if (a !== -1 && b !== -1 && b > a) {
  next = html.slice(0, a) + block + html.slice(b + END.length);
} else if (a === -1 && b === -1) {
  // First run: replace the old hand-written "Common Questions" block.
  const head = '<h2>Common Questions</h2>';
  const tail = '<h2>Need More Help?</h2>';
  const h = html.indexOf(head);
  const t = html.indexOf(tail);
  if (h === -1 || t === -1 || t < h) fail(`${PAGE}: no markers and no "Common Questions" block to replace`);
  next = html.slice(0, h) + block + '\n\n' + html.slice(t);
} else {
  fail(`${PAGE}: margin-help markers are unbalanced`);
}

if (next === html) {
  console.log(`margin-help: ok (${data.sections.length} sections, up to date)`);
  process.exit(0);
}
if (CHECK) {
  console.error('margin-help: margin/support.html is out of date. Run: node tools/margin-help.mjs <path-to-help.json>');
  process.exit(1);
}
writeFileSync(PAGE, next);
console.log(`margin-help: wrote ${path.relative(ROOT, PAGE)} (${data.sections.length} sections)`);
